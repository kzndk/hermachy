#!/usr/bin/env python3
"""Regenerate src/hermachy/attach_methods.py from a Hermes source checkout.

The bridge forwards only methods that the pinned Hermes release declares: the shared
OpenRPC contract plus the canonical session-authority verbs. A newer Hermes's new methods
are refused until this file is regenerated and their policy reviewed.

    python3 scripts/update_attach_methods.py /path/to/hermes-agent
"""
from __future__ import annotations

import json
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "src" / "hermachy" / "attach_methods.py"


def methods(source: Path) -> tuple[str, list[str]]:
    contract = json.loads((source / "apps" / "shared" / "src" / "gateway-contract.openrpc.json").read_text())
    names = {method["name"] for method in contract["methods"]}
    canonical = (source / "tui_gateway" / "contracts" / "canonical.py").read_text()
    names |= set(re.findall(r'^canonical_method\("([^"]+)"', canonical, flags=re.M))
    # Transport liveness verbs answered by the WebSocket loop itself.
    names |= {"gateway.ping", "ping"}
    revision = subprocess.run(["git", "-C", str(source), "rev-parse", "HEAD"], check=True,
                              capture_output=True, text=True).stdout.strip()
    return revision, sorted(names)


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    revision, names = methods(Path(sys.argv[1]).resolve())
    body = "".join(f"    {name!r},\n" for name in names)
    TARGET.write_text(
        '"""Generated by scripts/update_attach_methods.py; do not edit."""\n\n'
        f'HERMES_REVISION = "{revision}"\n\n'
        "DECLARED_METHODS = frozenset({\n" + body + "})\n"
    )
    print(f"{TARGET}: {len(names)} methods from {revision}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
